#!/usr/bin/env python3
"""Regenerate the committed shader headers of the presentation renderer.

Sources live in src/render/shaders/:
  vk_*.vert / vk_*.frag  Vulkan GLSL 450, compiled to SPIR-V with glslc -> SpirvShaders.h
  gl_*.vert / gl_*.frag  OpenGL GLSL bodies; #include lines are expanded and the text is
                         stored as C++ string literals -> GlslShaders.h (the #version
                         preamble, 410 core / 330 core / 150 core / 120, is prepended at
                         run time by OpenGLBackend.cpp)
  *.glsl                 code shared by both through #include

The generated headers are committed so that building OpenBRC does not need glslc.
Run this after editing a shader (the CMake target `shaders` does the same):

    python3 tools/gen_shaders.py [--glslc /path/to/glslc] [--check]

--check regenerates into memory and fails if the committed headers are out of date.
"""
import argparse
import os
import re
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src', 'render', 'shaders')
VK = ['vk_fullscreen.vert', 'vk_resolve.frag', 'vk_present.frag']
GL = ['gl_fullscreen.vert', 'gl_resolve.frag', 'gl_present.frag']
BANNER = ('// Generated by tools/gen_shaders.py from src/render/shaders/ -- do not edit.\n'
          '#pragma once\n')


def ident(prefix, name):
    """vk_present.frag -> kSpvPresentFrag"""
    stem, ext = name.split('_', 1)[1].split('.')
    return 'k%s%s%s' % (prefix, ''.join(p.capitalize() for p in stem.split('_')), ext.capitalize())


def expand(path, depth=0):
    if depth > 8:
        sys.exit('include nesting too deep at %s' % path)
    out = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            m = re.match(r'\s*#\s*include\s+"([^"]+)"', line)
            if m:
                out.append(expand(os.path.join(os.path.dirname(path), m.group(1)), depth + 1))
            else:
                out.append(line)
    return ''.join(out)


def cpp_string(text):
    rows = []
    for line in text.splitlines():
        rows.append('    "%s\\n"' % line.replace('\\', '\\\\').replace('"', '\\"'))
    return '\n'.join(rows)


def spirv(glslc, name, tmp):
    out = os.path.join(tmp, name + '.spv')
    cmd = [glslc, '--target-env=vulkan1.0', '-O', '-I', SRC, '-o', out, os.path.join(SRC, name)]
    subprocess.run(cmd, check=True)
    with open(out, 'rb') as f:
        data = f.read()
    return struct.unpack('<%dI' % (len(data) // 4), data)


def generate(glslc):
    spv = [BANNER, '\n#include <cstdint>\n\nnamespace brc::render::shaders {\n']
    with tempfile.TemporaryDirectory() as tmp:
        for name in VK:
            words = spirv(glslc, name, tmp)
            body = ',\n'.join('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8])
                              for i in range(0, len(words), 8))
            spv.append('\n// %s\ninline constexpr std::uint32_t %s[] = {\n%s,\n};\n'
                       % (name, ident('Spv', name), body))
    spv.append('\n} // namespace brc::render::shaders\n')

    glsl = [BANNER, '\nnamespace brc::render::shaders {\n']
    for name in GL:
        glsl.append('\n// %s\ninline constexpr char %s[] =\n%s;\n'
                    % (name, ident('Glsl', name), cpp_string(expand(os.path.join(SRC, name)))))
    glsl.append('\n} // namespace brc::render::shaders\n')
    return {
        os.path.join(SRC, 'SpirvShaders.h'): ''.join(spv),
        os.path.join(SRC, 'GlslShaders.h'): ''.join(glsl),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--glslc', default='glslc', help='glslc executable (default: glslc on PATH)')
    ap.add_argument('--check', action='store_true', help='fail if the committed headers are stale')
    args = ap.parse_args()

    stale = []
    for path, text in generate(args.glslc).items():
        rel = os.path.relpath(path, ROOT)
        if args.check:
            try:
                with open(path, encoding='utf-8') as f:
                    if f.read() != text:
                        stale.append(rel)
            except FileNotFoundError:
                stale.append(rel)
            continue
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', rel)
    if stale:
        sys.exit('out of date (run tools/gen_shaders.py): ' + ', '.join(stale))


if __name__ == '__main__':
    main()
